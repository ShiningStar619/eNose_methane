def oc(*args: str) -> str:
    cmd = ["officecli", *args]
    r = subprocess.run(cmd, capture_output=True)
    out = (r.stdout or b"").decode("utf-8", "replace")
    err = (r.stderr or b"").decode("utf-8", "replace")
    if r.returncode not in (0, 2):
        raise RuntimeError(f"fail {r.returncode}: {' '.join(args[:8])}\n{out}\n{err}")
    return out


def add_p(before: str, text: str, *, bold: bool = False, size: str = "12pt", space_after: str = "6pt") -> None:
    args = [
        str(FILE),
        "/body",
        "--type",
        "paragraph",
        "--before",
        before,
        "--prop",
        f"text={text}",
        "--prop",
        f"size={size}",
        "--prop",
        f"spaceAfter={space_after}",
    ]
    if bold:
        args += ["--prop", "bold=true"]
    oc("add", *args)


def add_eq(before: str, formula: str) -> None:
    oc(
        "add",
        str(FILE),
        "/body",
        "--type",
        "equation",
        "--before",
        before,
        "--prop",
        "mode=display",
        "--prop",
        f"formula={formula}",
    )


def emit(before: str, blocks: list[tuple[str, str]], tag: str) -> None:
    for kind, val in blocks:
        if kind == "h":
            add_p(before, val, bold=True, space_after="8pt")
        elif kind == "p":
            add_p(before, val)
        elif kind == "eq":
            add_eq(before, val)
        else:
            raise ValueError(kind)
        print(tag, kind, len(val))


